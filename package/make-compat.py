#!/usr/bin/env python3
"""The README's compatibility list: one row per rule file, from
the rule files (roms/celeste/*.yaml) and the checksums build.ps1
computed (compatibility.csv beside this file, rule,name,md5).

usage: make-compat.py

Rewrites the part of README.md between the COMPAT_START and COMPAT_END
markers (added at the bottom the first time); the rest of the README is
written by hand and is left byte for byte. Only the games in mode
checkpoints (what the package ships). Columns: game, checksum,
the checkpoints at EASY / MEDIUM / HARD, then V / X for boss thresholds
(`boss 75%`-style checkpoints), free boss rooms (`no_rewind`), a button
patch (`patches`), lives (`lives`) and music (`keep`). Sorted by name.
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# the rule files: games/ in the source project, roms/celeste/ in the release
GAMES = HERE.parent / "games" if (HERE.parent / "games").is_dir() else HERE.parent / "roms" / "celeste"
README = HERE / "README.md"
CSV = HERE / "compatibility.csv"
COMPAT_START = "<!-- compatibility list: generated by make-compat.py, edits here are overwritten -->"
COMPAT_END = "<!-- end of the compatibility list -->"

EXPLAIN = """## Compatibility list

Every game below is supported in one exact version: the installer checks
the ROM's checksum (MD5 of the ROM without its header) and only
installs that one. V: the game has it, X: not yet.

- **checkpoints**: how many at EASY / MEDIUM / HARD;
- **boss %**: checkpoints on the bosses' health (75, 50, 25 %);
- **free boss rooms**: on EASY, a hit in a boss room only costs health;
- **Select**: a button patch (Mega Man: every weapon, the last castle);
- **lives**: the lives counter shows the deaths;
- **music**: the music plays on across a rewind.
"""

LEVELS = ("easy", "medium", "hard")


def counts(text: str) -> str:
    """The checkpoints at each level: one without `levels:` counts at all three."""
    n = dict.fromkeys(LEVELS, 0)
    for block in re.split(r"(?m)^  - name:", text.split("\ncheckpoints:", 1)[1])[1:]:
        lv = re.search(r"(?m)^    levels:[ \t]*(.*?)[ \t]*\r?$", block)
        for level in (lv.group(1).split() if lv else LEVELS):
            n[level] += 1
    return " / ".join(str(n[level]) for level in LEVELS)


def features(rule: Path) -> tuple[str, str, dict[str, bool]]:
    text = rule.read_text("utf-8")
    keys = set(re.findall(r"(?m)^([a-z_]+):", text))
    name = re.search(r'(?m)^name:[ \t]*"?([^"#\r\n]*?)"?[ \t]*(#.*)?\r?$', text)
    if not name or "checkpoints" not in keys:
        raise SystemExit(f"make-compat: {rule.name} has no name: or no checkpoints:")
    return name.group(1), counts(text), {
        "boss %": bool(re.search(r"(?m)^  - name: .* boss \d+%", text)),
        "free boss rooms": "no_rewind:" in text,
        "Select": "patches" in keys,
        "lives": "lives" in keys,
        "music": "keep" in keys,
    }


def table() -> str:
    sums: dict[str, str] = {}
    with CSV.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            sums[row["rule"]] = row["md5"]
    rows: list[tuple[str, str, str, str, dict[str, bool]]] = []
    # games out of the release for now (disabled.txt beside this file)
    off = set((HERE / "disabled.txt").read_text("utf-8").split("\n")) if (HERE / "disabled.txt").exists() else set()
    for rule in sorted(GAMES.glob("*.yaml")):
        if rule.name in off:
            continue
        if rule.name not in sums:
            raise SystemExit(f"make-compat: {rule.name} is not in {CSV.name}: run celeste.sh package")
        name, cps, feats = features(rule)
        rows.append((name.casefold(), name, sums[rule.name], cps, feats))
    rows.sort(key=lambda r: r[0])
    cols = ["boss %", "free boss rooms", "Select", "lives", "music"]
    lines = ["| game | checksum | checkpoints | " + " | ".join(cols) + " |",
             "| --- | --- | :-: | " + " | ".join(":-:" for _ in cols) + " |"]
    for _, name, rule_md5, cps, feats in rows:
        lines.append(f"| {name} | `{rule_md5}` | {cps} | " + " | ".join("V" if feats[c] else "X" for c in cols) + " |")
    return EXPLAIN + "\n" + "\n".join(lines) + "\n"


def main() -> None:
    text = README.read_text("utf-8")
    block = COMPAT_START + "\n\n" + table() + "\n" + COMPAT_END + "\n"
    if COMPAT_START in text:
        start = text.index(COMPAT_START)
        end = text.index(COMPAT_END, start) + len(COMPAT_END)
        end += 1 if text[end:end + 1] == "\n" else 0
        new = text[:start] + block + text[end:]
    else:
        new = text.rstrip("\n") + "\n\n" + block
    if new != text:
        README.write_text(new, "utf-8")
    print(f"make-compat: {sum(1 for _ in GAMES.glob('*.yaml'))} games, README {'updated' if new != text else 'unchanged'}", file=sys.stderr)


if __name__ == "__main__":
    main()
